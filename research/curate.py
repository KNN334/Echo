def entry(doi, journal, zh, group, relevance, priority, work, result, innovation, limits, basis, use, data='', full=''):
    r = records[doi.lower()]
    authors = [a.get('fullName','') for a in r.get('authorList',{}).get('author',[])]
    short = ', '.join(authors[:3]) + (', et al.' if len(authors)>3 else '')
    ji=r['journalInfo']
    issue = f"{ji.get('volume','')}" + (f"({ji['issue']})" if ji.get('issue') else '')
    year=ji.get('yearOfPublication', r.get('pubYear'))
    citation=f"{short} {r['title'].rstrip('.')}[J]. {journal}, {year}, {issue}: {r.get('pageInfo','')}. DOI: {doi}."
    online=r.get('electronicPublicationDate')
    first=r.get('firstPublicationDate')
    return dict(id=0,doi=doi,journal=journal,title=r['title'].rstrip('.'),zh=zh,authors=short,
      online=online or first, date_basis='电子发表日（数据库记录）' if online else '数据库首发日期；无独立电子发表日，日精度未确认',
      issue_date=ji.get('dateOfPublication',''),year=int(year),group=group,relevance=relevance,priority=priority,
      work=work,result=result,innovation=innovation,limits=limits,limit_basis=basis,use=use,
      data=data or '本轮未核实可直接使用的数据/代码；需检查原文可用性声明',
      evidence=full or 'Europe PMC题录与摘要；未完成全文及补充材料精读',
      url='https://doi.org/'+doi, record_url=f"https://europepmc.org/article/MED/{r['id']}",
      abstract=BeautifulSoup(r.get('abstractText','') or '', 'html.parser').get_text(' ',strip=True),citation=citation)

